def setup(doc):
    st = doc.styles['Normal']
    st.font.name = '微软雅黑'
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(
        __import__('docx').oxml.ns.qn('w:eastAsia'), '微软雅黑')
    for s in doc.sections:
        s.top_margin = Cm(2.0)
        s.bottom_margin = Cm(2.0)
        s.left_margin = Cm(2.2)
        s.right_margin = Cm(2.2)


def h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        r.font.color.rgb = RGBColor(0x1A, 0x1A, 0x1A)
        r.font.name = '微软雅黑'
    return p


def para(doc, text, bold=False, size=10.5, color=None, space_after=4):
    """支持 **加粗** 标记。直接写字面 ** 会在 Word 里显示成星号，很难看。"""
    p = doc.add_paragraph()
    for i, seg in enumerate(text.split('**')):
        if not seg:
            continue
        r = p.add_run(seg)
        r.bold = bold or (i % 2 == 1)
        r.font.size = Pt(size)
        if color:
            r.font.color.rgb = color
    p.paragraph_format.space_after = Pt(space_after)
    return p


def cell_text(cell, text, size=9, bold=False):
    """表格单元格：同样支持 **加粗**。"""
    cell.text = ''
    par = cell.paragraphs[0]
    for i, seg in enumerate(str(text).split('**')):
        if not seg:
            continue
        r = par.add_run(seg)
        r.bold = bold or (i % 2 == 1)
        r.font.size = Pt(size)


